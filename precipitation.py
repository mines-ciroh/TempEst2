def get_precipitation(lon, lat, start, end):
    """Retrieve precipitation data for a given point and date range."""
    region = ee.Geometry.Point(lon, lat)

    dataset = ee.ImageCollection('NASA/NLDAS/FORA0125_H002') \
        .filterDate(start, end) \
        .select('total_precipitation')

    precip = dataset.reduce(ee.Reducer.sum()).clip(region)

    result = precip.reduceRegion(
        reducer=ee.Reducer.mean(),
        geometry=region,
        scale=5000,
        maxPixels=1e9
    ).getInfo()

    # Checks if the precipitation data is available
    if 'total_precipitation_sum' not in result:
        print(f"No precipitation data found for {start} - {end}")
        return None

    return result['total_precipitation_sum']

def write_precipitation_to_csv(output_file, datapts, date_range):
    """Collect precipitation data and write to CSV."""
    with open(output_file, mode='w', newline='') as csvfile:
        fieldnames = ['point_id', 'lon', 'lat', 'date', 'precipitation']
        writer = csv.DictWriter(csvfile, fieldnames=fieldnames)
        writer.writeheader()

        for pt in datapts:
            lon, lat = pt[0]
            point_id = pt[1]

            for date in date_range:
                start = date.strftime('%Y-%m-%d')
                end = (date + dt.timedelta(days=1)).strftime('%Y-%m-%d')

                try:
                    precip_value = get_precipitation(lon, lat, start, end)
                    if precip_value is not None:
                        writer.writerow({
                            'point_id': point_id,
                            'lon': lon,
                            'lat': lat,
                            'date': start,
                            'precipitation': precip_value
                        })
                        print(f"Data written for {point_id} on {start}")
                except Exception as e:
                    print(f"Error retrieving data for {point_id} on {start}: {e}")

